/**
 * Everything that must be true before a single browser opens.
 *
 * Run as its own step rather than from Playwright's `globalSetup`, because the
 * ordering of globalSetup against `webServer` is not something to depend on:
 * the API cannot start until its database exists, and a race there would show
 * up as a flaky suite rather than as an error.
 *
 * What it builds:
 *
 *   - A DEDICATED database, dropped and recreated from the real Alembic
 *     migrations. Never the developer's own: the suite truncates between tests.
 *   - A dedicated storage root, emptied. Resume uploads and tailored artifacts
 *     both live here, so a stale artifact from a previous run cannot make a
 *     download assertion pass.
 *   - The fixture PDF, generated by the SAME builder the pytest suite uses, so
 *     the browser uploads a document the extractor is genuinely known to read.
 *   - A production build, because the suite drives `next start`. Testing the
 *     dev server would be testing a bundler.
 */

import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { existsSync, mkdirSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const { E2E, PYTHON, API_DIR, WEB_DIR } = createRequire(import.meta.url)("./env.cjs");

const HERE = dirname(fileURLToPath(import.meta.url));

function run(label, file, args, options = {}) {
  process.stdout.write(`  ${label}… `);
  try {
    execFileSync(file, args, { stdio: "pipe", ...options });
    process.stdout.write("ok\n");
  } catch (error) {
    process.stdout.write("FAILED\n");
    const detail = [error.stdout?.toString(), error.stderr?.toString()]
      .filter(Boolean)
      .join("\n");
    throw new Error(`${label} failed:\n${detail || error.message}`);
  }
}

console.log("Preparing the end-to-end environment");

// 1. A database of its own, built the way production is built.
run("recreating the test database", PYTHON, [resolve(HERE, "db_admin.py"), "recreate"], {
  cwd: API_DIR,
  env: { ...process.env, E2E_DATABASE_URL: E2E.databaseUrl },
});

run("applying migrations", PYTHON, ["-m", "alembic", "upgrade", "head"], {
  cwd: API_DIR,
  env: { ...process.env, DATABASE_URL: E2E.databaseUrl },
});

// 2. A storage root of its own, empty. A left-over artifact would let a
//    download assertion pass against a file this run never produced.
rmSync(E2E.storageRoot, { recursive: true, force: true });
mkdirSync(E2E.storageRoot, { recursive: true });
mkdirSync(E2E.downloadDir, { recursive: true });
console.log("  clearing storage and downloads… ok");

// 3. The fixture resume, from the builder the pytest suite already trusts.
run("generating the fixture resume", PYTHON, [
  resolve(HERE, "db_admin.py"),
  "make-resume",
  E2E.fixtureResume,
], { cwd: API_DIR });

run("generating the golden resume", PYTHON, [
  resolve(HERE, "db_admin.py"),
  "make-golden-resume",
  E2E.goldenResume,
], { cwd: API_DIR });

// 4. A production build. `next start` serves this; both identity servers share it.
if (process.env.E2E_SKIP_BUILD === "1" && existsSync(resolve(WEB_DIR, E2E.distDir, "BUILD_ID"))) {
  console.log("  building the web app… skipped (E2E_SKIP_BUILD=1)");
} else {
  // Next's own entry point, through node. Not `npm run build`: since Node
  // 20.12 `spawnSync` refuses to launch a `.cmd` without a shell, and going
  // through a shell to reach a JavaScript file is two problems where there
  // were none.
  // Resolved rather than guessed: npm workspaces hoist `next` to the repo
  // root, so a path under apps/web/node_modules is right on some checkouts and
  // wrong on others.
  const nextBin = createRequire(import.meta.url).resolve("next/dist/bin/next");

  // One build, served by both identity servers. They only read it.
  // Its own build directory, so a development server rewriting `.next` next
  // door cannot overwrite what `next start` is about to serve.
  run("building the web app", process.execPath, [nextBin, "build"], {
    cwd: WEB_DIR,
    env: { ...process.env, NEXT_DIST_DIR: E2E.distDir },
  });
}

console.log("Ready.\n");
