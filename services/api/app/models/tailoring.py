"""The tailoring domain: turning a confirmed profile version into a document
aimed at one job.

Four tables, and the split between them is the whole honesty story of this
feature:

    TailoringRun            one attempt. A process record: which snapshot, which
                            requirements, which generator, what state it reached
                            and where it failed. Append-only — a retry is a new
                            row, never a reset of this one.

    TailoredResume          what the generator produced, as a validated JSONB
                            document, plus the VERDICT of grounding validation.
                            Written even when grounding failed, because "here is
                            what it wrote and here is why we will not stand
                            behind it" is more useful — and more honest — than
                            discarding the evidence.

    TailoringIssue          one grounding finding. An `error` means a claim the
                            source snapshot does not support; a `warning` means
                            something a reader should check. Errors are what
                            withhold the artifact.

    TailoredResumeArtifact  the rendered file, by storage key. Exists only for a
                            document that passed grounding, which is what makes
                            "an invalid artifact cannot be downloaded" a fact
                            about the schema rather than a check someone has to
                            remember to write.

Reproducibility follows the matching domain's pattern exactly, and for the same
reasons — see app/models/match.py:

  * `profile_version_id` pins an immutable snapshot, so what was tailored FROM
    cannot move underneath the result. Drafts are refused in the service layer.
  * `job_requirements_id` pins the exact structured reading of the posting that
    the generator was aimed at, not the job, because reprocessing a job writes a
    new requirements row.
  * `generator` / `model` / `prompt_version` / `schema_version` record what
    produced the text. A document generated by a regex and one generated by a
    model are different claims, and a reader six months from now needs to know
    which they are looking at.

There is deliberately no unique constraint making a (version, requirements)
pair tailorable only once. A match is a judgment — asking twice should give the
same answer — but a tailored document is a DRAFT the user may legitimately want
regenerated. `attempt` orders them and the newest is the one the UI shows.
"""

from datetime import datetime
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

# --- the state machine --------------------------------------------------------
#
# One `failed` state with a `failed_stage` column, the same shape the resume
# domain uses and for the same reason: every failure is terminal and the retry
# is a new run, so a failure state per stage would multiply the transition table
# without expressing anything new.
#
# `validating` is its own state rather than a step inside `generating` because
# it is the state a run can END in having produced something: a document that
# failed grounding reaches `completed` with `grounding_status = 'failed'` and no
# artifact. That is not a processing failure — the pipeline worked exactly as
# intended — and collapsing the two would make the UI unable to tell "we could
# not generate this" from "we generated it and will not vouch for it".

STATUS_QUEUED = "queued"
STATUS_GENERATING = "generating"
STATUS_VALIDATING = "validating"
STATUS_RENDERING = "rendering"
STATUS_COMPLETED = "completed"
STATUS_FAILED = "failed"

INITIAL_STATUS = STATUS_QUEUED

TERMINAL_STATUSES = frozenset({STATUS_COMPLETED, STATUS_FAILED})

ALLOWED_TRANSITIONS: dict[str, frozenset[str]] = {
    STATUS_QUEUED: frozenset({STATUS_GENERATING, STATUS_FAILED}),
    STATUS_GENERATING: frozenset({STATUS_VALIDATING, STATUS_FAILED}),
    # Grounding decides which way this goes. Passed -> render the artifact.
    # Failed -> complete WITHOUT one, carrying the issues that say why.
    STATUS_VALIDATING: frozenset({STATUS_RENDERING, STATUS_COMPLETED, STATUS_FAILED}),
    STATUS_RENDERING: frozenset({STATUS_COMPLETED, STATUS_FAILED}),
    STATUS_COMPLETED: frozenset(),
    STATUS_FAILED: frozenset(),
}

ALL_STATUSES = tuple(ALLOWED_TRANSITIONS)

#: Stage names for failed_stage and for the event log.
STAGES = ("generate", "validate", "render")

# --- the grounding verdict ----------------------------------------------------
#
# Two values, not three. "Partially grounded" was considered and rejected: a
# document either has an unsupported claim in it or it does not, and softening
# that into a spectrum is precisely how a generated sentence ends up being
# presented as a verified fact.

GROUNDING_PASSED = "passed"
GROUNDING_FAILED = "failed"

GROUNDING_STATUSES = (GROUNDING_PASSED, GROUNDING_FAILED)

# --- how serious a grounding finding is ---------------------------------------

SEVERITY_ERROR = "error"
SEVERITY_WARNING = "warning"

SEVERITIES = (SEVERITY_ERROR, SEVERITY_WARNING)

#: Which generator wrote the document. Mirrors the resume domain's `structurer`.
GENERATOR_DETERMINISTIC = "deterministic"
GENERATOR_AI = "ai"

GENERATORS = (GENERATOR_DETERMINISTIC, GENERATOR_AI)

_STATUS_SQL = ", ".join(f"'{value}'" for value in ALL_STATUSES)
_STAGE_SQL = ", ".join(f"'{value}'" for value in STAGES)
_GROUNDING_SQL = ", ".join(f"'{value}'" for value in GROUNDING_STATUSES)
_SEVERITY_SQL = ", ".join(f"'{value}'" for value in SEVERITIES)
_GENERATOR_SQL = ", ".join(f"'{value}'" for value in GENERATORS)


class TailoringRun(Base):
    """One attempt at generating a tailored resume."""

    __tablename__ = "tailoring_runs"

    __table_args__ = (
        UniqueConstraint(
            "job_id",
            "profile_version_id",
            "attempt",
            name="uq_tailoring_runs_job_version_attempt",
        ),
        CheckConstraint("attempt > 0", name="ck_tailoring_runs_attempt_positive"),
        CheckConstraint(f"status IN ({_STATUS_SQL})", name="ck_tailoring_runs_status"),
        CheckConstraint(
            f"failed_stage IS NULL OR failed_stage IN ({_STAGE_SQL})",
            name="ck_tailoring_runs_failed_stage",
        ),
        CheckConstraint(
            f"generator IN ({_GENERATOR_SQL})", name="ck_tailoring_runs_generator"
        ),
        # A failure names where it happened and why; a success claims neither.
        CheckConstraint(
            "(status = 'failed') = (failed_stage IS NOT NULL)",
            name="ck_tailoring_runs_failed_stage_matches_status",
        ),
        CheckConstraint(
            "(status = 'failed') = (error_code IS NOT NULL)",
            name="ck_tailoring_runs_error_code_matches_status",
        ),
        CheckConstraint(
            "(status IN ('completed', 'failed')) = (finished_at IS NOT NULL)",
            name="ck_tailoring_runs_finished_at_matches_status",
        ),
        # "My tailored resumes", the listing endpoint's only query.
        Index("ix_tailoring_runs_user_id_created_at", "user_id", "created_at"),
        # "This job's tailored resumes", the job detail page's query.
        Index("ix_tailoring_runs_user_id_job_id", "user_id", "job_id"),
        # Which runs are still outstanding. Partial, because almost every row
        # is terminal and terminal rows are never work.
        Index(
            "ix_tailoring_runs_active",
            "created_at",
            postgresql_where=text("status NOT IN ('completed', 'failed')"),
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)

    # Denormalized from profile_versions -> profiles -> user_id so every
    # ownership check is one predicate on this table, exactly as MatchResult
    # does it. The service still resolves ownership from the profile side when
    # CREATING a run; this column is how reads stay scoped cheaply.
    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="RESTRICT", name="fk_tailoring_runs_user_id"),
        nullable=False,
    )

    # CASCADE: a tailored resume is meaningless without the job it was aimed at.
    job_id: Mapped[int] = mapped_column(
        ForeignKey("jobs.id", ondelete="CASCADE", name="fk_tailoring_runs_job_id"),
        nullable=False,
    )

    # RESTRICT: the snapshot is what the document claims to be grounded in.
    # Losing it would leave every generated sentence unverifiable.
    profile_version_id: Mapped[int] = mapped_column(
        ForeignKey(
            "profile_versions.id",
            ondelete="RESTRICT",
            name="fk_tailoring_runs_profile_version_id",
        ),
        nullable=False,
        index=True,
    )

    # The exact structured reading the generator was aimed at.
    job_requirements_id: Mapped[int] = mapped_column(
        ForeignKey(
            "job_requirements.id",
            ondelete="RESTRICT",
            name="fk_tailoring_runs_job_requirements_id",
        ),
        nullable=False,
        index=True,
    )

    # The match that motivated this, when there was one. Nullable and SET NULL
    # rather than required: tailoring is useful without having matched first,
    # and a match is a convenience input (it says which requirements to lead
    # with), never a precondition.
    match_result_id: Mapped[int | None] = mapped_column(
        ForeignKey(
            "match_results.id",
            ondelete="SET NULL",
            name="fk_tailoring_runs_match_result_id",
        ),
        nullable=True,
    )

    attempt: Mapped[int] = mapped_column(Integer, nullable=False, default=1)

    status: Mapped[str] = mapped_column(
        String(16), nullable=False, server_default=INITIAL_STATUS
    )

    # What wrote it. Recorded on the run rather than only on the document so a
    # FAILED attempt still says which generator failed.
    generator: Mapped[str] = mapped_column(String(16), nullable=False)
    model: Mapped[str | None] = mapped_column(String(64), nullable=True)
    prompt_version: Mapped[str | None] = mapped_column(String(16), nullable=True)
    # The provider adapter that answered, and what the call cost — mirroring
    # `job_requirements` and `resume_structured_results`. NULL for the
    # deterministic generator, which calls nothing. The metadata is counts,
    # identifiers and timings only: never the prompt, never the completion,
    # never a key. Not exposed by any API schema; it is for whoever audits a
    # run's cost or asks why a completion stopped, not for the review screen.
    provider: Mapped[str | None] = mapped_column(String(64), nullable=True)
    provider_metadata: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)

    failed_stage: Mapped[str | None] = mapped_column(String(16), nullable=True)
    error_code: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # Our own words, from a fixed vocabulary — never str(exception). A provider
    # error quotes the prompt, and the prompt contains the user's resume.
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    result: Mapped["TailoredResume | None"] = relationship(
        back_populates="run",
        cascade="all, delete-orphan",
        uselist=False,
    )

    # Read-only, and with no back_populates on Job. A listing needs the job
    # title to be recognisable and re-querying per row would be an N+1; giving
    # Job a `tailoring_runs` collection in exchange would put a growing list of
    # generated documents on an object the job domain loads constantly.
    job: Mapped["Job"] = relationship(viewonly=True)  # noqa: F821

    def __repr__(self) -> str:
        return (
            f"<TailoringRun id={self.id} job={self.job_id} "
            f"version={self.profile_version_id} status={self.status!r}>"
        )

    @property
    def is_terminal(self) -> bool:
        return self.status in TERMINAL_STATUSES


class TailoredResume(Base):
    """The generated document, and whether we stand behind it.

    `payload` is the whole document as one JSONB column rather than a set of
    relational section tables — the opposite choice from `match_requirement_
    results`, and deliberately so. A tailored resume is read whole, always,
    rendered whole, and never queried by individual bullet; nothing asks "which
    bullets mention Kubernetes across all my tailored resumes". A JSONB document
    validated on the way in and re-validated on the way out is the right shape
    for data with those access patterns, exactly as `job_requirements.payload`
    is.

    The grounding issues are the exception and DO get their own table: they are
    counted, filtered by severity, and shown next to the section they concern.
    """

    __tablename__ = "tailored_resumes"

    __table_args__ = (
        UniqueConstraint("tailoring_run_id", name="uq_tailored_resumes_run_id"),
        CheckConstraint(
            f"grounding_status IN ({_GROUNDING_SQL})",
            name="ck_tailored_resumes_grounding_status",
        ),
        CheckConstraint(
            "error_count >= 0 AND warning_count >= 0",
            name="ck_tailored_resumes_counts_not_negative",
        ),
        # The rule that makes the verdict mean something: a document with an
        # unsupported claim in it cannot be recorded as grounded. Enforced here
        # rather than only in Python because the pipeline is not the only thing
        # that will ever write this table.
        CheckConstraint(
            "(grounding_status = 'passed') = (error_count = 0)",
            name="ck_tailored_resumes_passed_has_no_errors",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)

    tailoring_run_id: Mapped[int] = mapped_column(
        ForeignKey(
            "tailoring_runs.id",
            ondelete="CASCADE",
            name="fk_tailored_resumes_tailoring_run_id",
        ),
        nullable=False,
    )

    # Validated against app/schemas/tailored_resume.py before it is written, and
    # re-validated on the way out. A payload that has been through JSONB is not
    # a payload that has been through the model.
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)

    #: Which shape `payload` was validated against.
    schema_version: Mapped[str] = mapped_column(String(16), nullable=False)

    grounding_status: Mapped[str] = mapped_column(String(16), nullable=False)
    error_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    warning_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    run: Mapped["TailoringRun"] = relationship(back_populates="result")

    issues: Mapped[list["TailoringIssue"]] = relationship(
        back_populates="tailored_resume",
        cascade="all, delete-orphan",
        order_by="TailoringIssue.id",
    )

    artifact: Mapped["TailoredResumeArtifact | None"] = relationship(
        back_populates="tailored_resume",
        cascade="all, delete-orphan",
        uselist=False,
    )

    def __repr__(self) -> str:
        return (
            f"<TailoredResume id={self.id} run={self.tailoring_run_id} "
            f"grounding={self.grounding_status!r}>"
        )


class TailoringIssue(Base):
    """One thing grounding validation found.

    `claim` is the generated text that is in question and `reason` is our own
    words for what is wrong with it. Both are stored rather than recomputed
    because the point of this table is to be readable later, by a person, next
    to the sentence it concerns — and because re-running the validator against
    a stored payload would answer today's question, not the one that was
    actually asked when the document was produced.
    """

    __tablename__ = "tailoring_issues"

    __table_args__ = (
        CheckConstraint(f"severity IN ({_SEVERITY_SQL})", name="ck_tailoring_issues_severity"),
        CheckConstraint("char_length(reason) > 0", name="ck_tailoring_issues_reason_present"),
        CheckConstraint("char_length(section) > 0", name="ck_tailoring_issues_section_present"),
        Index("ix_tailoring_issues_severity", "tailored_resume_id", "severity"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)

    tailored_resume_id: Mapped[int] = mapped_column(
        ForeignKey(
            "tailored_resumes.id",
            ondelete="CASCADE",
            name="fk_tailoring_issues_tailored_resume_id",
        ),
        nullable=False,
        index=True,
    )

    severity: Mapped[str] = mapped_column(String(16), nullable=False)

    #: Which part of the document — "summary", "experience", "skills".
    section: Mapped[str] = mapped_column(String(32), nullable=False)
    #: Where exactly, as a readable path: "experience[1].bullets[0]".
    field_path: Mapped[str | None] = mapped_column(String(128), nullable=True)

    #: The generated text this is about. Truncated, never paraphrased.
    claim: Mapped[str | None] = mapped_column(String(600), nullable=True)
    #: Why it is a problem. Our words, from the vocabulary in grounding.py.
    reason: Mapped[str] = mapped_column(String(400), nullable=False)

    tailored_resume: Mapped["TailoredResume"] = relationship(back_populates="issues")

    def __repr__(self) -> str:
        return f"<TailoringIssue {self.severity} {self.section} {self.reason!r}>"


class TailoredResumeArtifact(Base):
    """The rendered file.

    Holds a storage KEY, never a path and never bytes — see
    app/services/storage.py for why the application is not allowed to know where
    an object lives, and §10 for why a document binary does not go in
    PostgreSQL.

    A row here exists only for a document that passed grounding. The pipeline
    skips rendering otherwise, so "the artifact exists" and "the document is
    one we will stand behind" are the same fact rather than two that could
    disagree.
    """

    __tablename__ = "tailored_resume_artifacts"

    __table_args__ = (
        UniqueConstraint(
            "tailored_resume_id", name="uq_tailored_resume_artifacts_tailored_resume_id"
        ),
        CheckConstraint("byte_size > 0", name="ck_tailored_resume_artifacts_byte_size_positive"),
        CheckConstraint(
            "char_length(storage_key) > 0",
            name="ck_tailored_resume_artifacts_storage_key_present",
        ),
        CheckConstraint(
            "char_length(content_sha256) = 64",
            name="ck_tailored_resume_artifacts_sha256_length",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)

    tailored_resume_id: Mapped[int] = mapped_column(
        ForeignKey(
            "tailored_resumes.id",
            ondelete="CASCADE",
            name="fk_tailored_resume_artifacts_tailored_resume_id",
        ),
        nullable=False,
    )

    # Opaque. Never exposed by any API schema — see app/schemas/tailoring.py.
    storage_key: Mapped[str] = mapped_column(String(512), nullable=False)

    # What to call the file when it reaches the user, and what to say it is.
    # Derived server-side from the job and the version; never from client input.
    filename: Mapped[str] = mapped_column(String(255), nullable=False)
    media_type: Mapped[str] = mapped_column(String(128), nullable=False)

    byte_size: Mapped[int] = mapped_column(Integer, nullable=False)
    content_sha256: Mapped[str] = mapped_column(String(64), nullable=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    tailored_resume: Mapped["TailoredResume"] = relationship(back_populates="artifact")

    def __repr__(self) -> str:
        return f"<TailoredResumeArtifact id={self.id} {self.filename!r} {self.byte_size}B>"
